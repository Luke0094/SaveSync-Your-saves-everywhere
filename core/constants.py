def _with_plural_list(words) -> list[str]:
    """Ordered, de-duplicated expansion of *words* with their simple English
    plural (trailing 's'), first-seen order preserved. Lets a keyword list
    name each word once instead of both forms by hand ("save" also yields
    "saves", "profile"→"profiles"); a word already ending in 's' is emitted
    unchanged. List form for call sites that iterate or extend the result."""
    out: list[str] = []
    for w in words:
        wl = (w or "").lower()
        if not wl or wl in out:
            continue
        out.append(wl)
        if not wl.endswith('s'):
            pl = wl + 's'
            if pl not in out:
                out.append(pl)
    return out


