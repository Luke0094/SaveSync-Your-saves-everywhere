def strip_version_tokens(name: str) -> str:
    """Remove version/build markers and DLsite product codes from a
    game/folder name: ``v1.2``, ``V0.5.3b``, ``ver 2``, ``version 3.0``,
    ``b12``, ``build 15``, ``Build-2024.1``, ``v1,27`` (a comma sat where a
    period belongs — seen on a real release), ``[RJ123456]``/``RE``/``VJ``
    codes — these change across game updates or disappear on other
    stores while the game stays the same, so identity comparisons
    (remote backup folders, search queries) must ignore them. The code
    prefixes are the DLsite product-code family ((RJ|RE|VJ) + 4-10 digits).

    Bare numbers and roman numerals are deliberately preserved:
    "Example Game 3", "Example Game V" and "Example Game RE4" keep their
    sequel identity (version markers must be followed by digits; DLsite
    codes need at least 4 digits).
    """
    import re
    if not name:
        return name
    # (?<![a-zA-Z0-9]) instead of \b: underscores are word chars, so \b never
    # fires in names like "MyGame_v0.5_build12". The trailing
    # (?![a-zA-Z0-9]) keeps tokens whole: "V2ray" and "RJ123456abc" are
    # names, not markers; "v0.5b" (single letter suffix) is still one.
    cleaned = re.sub(
        r'[\s._\-\(\[]*(?<![a-zA-Z0-9])'
        r'(?:(?:v(?:er(?:sion)?)?|b(?:uild)?)[\s._\-]*\d+(?:[._\-,]\d+)*[a-z]?'
        r'|(?:RJ|RE|VJ)\d{4,10})'
        r'(?![a-zA-Z0-9])[\)\]]*',
        ' ', name, flags=re.IGNORECASE,
    )
    cleaned = re.sub(r'\s{2,}', ' ', cleaned).strip(' ._-')
    return cleaned or name


def strip_dlsite_code(name: str) -> str:
    """Remove a DLsite product code (RJ/RE/VJ + 4-10 digits) from *name*,
    bracketed or not — the same token strip_version_tokens already
    recognizes, isolated here for callers that want the code gone but the
    VERSION kept (strip_version_tokens's own drop_version removes both
    together; _strip_release_noise's bracket stripper only catches a
    BRACKETED code, e.g. "[RJ123456]" — an unbracketed leading one like
    "RJ123456 Some Title v1.0" sails straight through it otherwise).
    """
    import re
    if not name:
        return name
    cleaned = re.sub(
        r'[\s._\-\(\[]*(?<![a-zA-Z0-9])(?:RJ|RE|VJ)\d{4,10}(?![a-zA-Z0-9])[\)\]]*',
        ' ', name, flags=re.IGNORECASE,
    )
    cleaned = re.sub(r'\s{2,}', ' ', cleaned).strip(' ._-')
    return cleaned or name


def extract_version_token(name: str) -> str:
    """The version marker itself out of *name* — "v1.2.3" out of
    "[GOG] Some Title v1.2.3-CODEX" — or "" when none is found.

    The inverse of strip_version_tokens: that one throws the marker away
    and keeps the title; this one IS the marker, for the one place that
    wants to show the version and nothing else (not a DLsite product code
    — those identify a release, not a version, so unlike
    strip_version_tokens this deliberately doesn't match them).
    """
    import re
    if not name:
        return ""
    m = re.search(
        r'(?<![a-zA-Z0-9])((?:v(?:er(?:sion)?)?|b(?:uild)?)[\s._\-]*\d+(?:[._\-,]\d+)*[a-z]?)'
        r'(?![a-zA-Z0-9])',
        name, flags=re.IGNORECASE,
    )
    return m.group(1).strip() if m else ""


# The kana voiced/semi-voiced sound marks. Combining characters, but part of
# the letter rather than an accent on it — see match_slug.
_KANA_VOICING = ("゙", "゚")


def match_slug(name: str) -> str:
    """A name reduced to its letters and digits, for comparing two names.

    Keeps letters and digits in ANY script, which is the whole point. The
    rule this replaces was ``[^a-z0-9]`` — it deleted every character that
    was not a plain ASCII letter or digit, so a title written entirely in
    Japanese, Chinese, Korean, Russian or Greek slugged down to the empty
    string and could never be matched against the folder it saves into,
    however exactly the two names agreed.

    Accents are FOLDED rather than kept, and that is not a detail. A game
    called ``Café`` very often installs into a folder called ``Cafe``, and a
    slug that kept the accent would stop matching the two — worse than the
    rule it replaces, which at least reduced both to something shared. So
    the name is decomposed and its combining marks dropped first: ``Café``
    and ``Cafe`` both become ``cafe``. Full-width and ligature forms fold the
    same way, which is what NFKD is for.

    Japanese voicing marks are the one exception, and they have to be. A
    dakuten is a combining mark like an acute accent is, but it is not
    decoration: ``ゲ`` and ``ケ`` are different kana, the way ``b`` and ``p``
    are different letters. Dropping it with the accents would fold apart
    games that merely sound alike, so it is kept and put back.

    ASCII names come out exactly as they did before.
    """
    import unicodedata
    text = unicodedata.normalize("NFKD", (name or "").lower())
    kept = "".join(ch for ch in text
                   if ch in _KANA_VOICING or not unicodedata.combining(ch))
    return "".join(ch for ch in unicodedata.normalize("NFC", kept)
                   if ch.isalnum())


# Scripts that pack a word into far fewer characters than Latin does: the
# kana, the CJK ideographs, and the hangul syllables. Used by slug_weight.
_DENSE_SCRIPTS = (
    (0x3040, 0x30FF),   # hiragana and katakana
    (0x3400, 0x4DBF),   # CJK unified ideographs, extension A
    (0x4E00, 0x9FFF),   # CJK unified ideographs
    (0xF900, 0xFAFF),   # CJK compatibility ideographs
    (0xAC00, 0xD7AF),   # hangul syllables
)


def slug_weight(slug: str) -> int:
    """How distinctive a slug is, measured in Latin-equivalent characters.

    Every "is this name specific enough to match on?" test used to count
    characters, which was the same thing as counting Latin letters because a
    slug could not hold anything else. Now that it can, counting characters
    measures the wrong thing: a three-character Japanese title carries about
    as much as a six-letter English one, so a plain length test rejects names
    that are perfectly distinctive and would quietly stop matching them.

    A kana, an ideograph or a hangul syllable therefore counts double.
    Cyrillic and Greek do NOT — a letter there is a letter, the same as in
    Latin — so they keep counting one, and ASCII is unchanged.
    """
    return sum(2 if any(lo <= ord(ch) <= hi for lo, hi in _DENSE_SCRIPTS)
               else 1
               for ch in (slug or ""))


def version_insensitive_slug(name: str) -> str:
    """Lowercase alphanumeric slug with version/build tokens removed — the
    comparison key for "same game, different version suffix".

    Built on match_slug, so a game named in a non-Latin script has a key at
    all. It did not before, and the consequence was not cosmetic: this is how
    a game is matched to the cloud folder holding its backups, and an empty
    key matched nothing, so those backups could not be found. Nothing stores
    this value — every caller computes it fresh on both sides of a
    comparison — so widening it matches more without stranding anything.
    """
    return match_slug(strip_version_tokens(name or ''))


_TOKEN_AFTER_BOUNDARY_RE = re.compile(r'[A-Za-z0-9]+')


def _looks_like_sequel_marker(token: str) -> bool:
    """True when *token* (the word right after a matched name prefix)
    reads as a sequel/entry number rather than a subtitle — "2", "VII"
    and the like. A digit or a multi-letter roman numeral straight after
    the shared prefix means the games are related but distinct entries,
    not the same game under a grown title.

    Reuses game_sources.common's own Roman-numeral table (built for
    matching search results against sequel titles) rather than a second
    one here; imported lazily — that module imports from this one at
    load time, so a top-level import would be circular. Single-letter
    "I"/"V"/"X" are deliberately not treated as numerals here either,
    same reasoning as there: in a title they are far more often a real
    word or initial than the number 1/5/10.
    """
    if not token:
        return False
    if token.isdigit():
        return True
    from core.game_sources.common import _ROMAN_TO_ARABIC
    return token.lower() in _ROMAN_TO_ARABIC


def names_probably_same_game(a: str, b: str) -> bool:
    """True when two game NAMES (not exe paths) probably name the same
    game — either an exact match once case/whitespace is ignored, or one
    is a clean PREFIX of the other.

    The prefix case is for a title that grew between releases: an early
    build tracked in the library under a short working title, a later one
    under its full release title with a subtitle appended.
    strip_version_tokens already handles a trailing VERSION growing; this
    handles the TITLE itself growing, which is a different kind of change
    and needs a different check.

    Deliberately checked on the raw names, not on version_insensitive_slug
    — slugging strips every space and punctuation mark, and a slug prefix
    check on THAT would happily match two names that only share a leading
    run of letters, with no word boundary left to say otherwise. Checked
    here on the lowercased names themselves instead, so the character
    right after the shorter name can be required to be a real boundary
    (space, dash, …), not another letter. A shorter name under 3
    characters is never trusted alone — too little to be real evidence
    either way.

    A prefix match is also rejected when the word immediately following
    the shared prefix is a bare number or a short roman numeral (e.g. the
    shorter name is "Game" and the longer is "Game 2" / "Game II") —
    that shape names a SEQUEL, a distinct entry in a series, not the same
    game grown a subtitle.
    """
    a_norm = (a or '').strip().lower()
    b_norm = (b or '').strip().lower()
    if not a_norm or not b_norm:
        return False
    if a_norm == b_norm:
        return True
    shorter, longer = (a_norm, b_norm) if len(a_norm) <= len(b_norm) else (b_norm, a_norm)
    if len(shorter) < 3 or not longer.startswith(shorter):
        return False
    boundary = longer[len(shorter):len(shorter) + 1]
    if boundary.isalnum():
        return False
    remainder = longer[len(shorter):].lstrip(string.whitespace + string.punctuation)
    next_token = _TOKEN_AFTER_BOUNDARY_RE.match(remainder)
    if next_token and _looks_like_sequel_marker(next_token.group(0)):
        return False
    return True


# Separator between a name and the tag that distinguishes it from another
# name spelled the same way. Survives _normalize_folder_name (which only
# rewrites <>:"/\|?* ) and is dropped by match_slug, so a tagged name shares
# no comparison key with anything else.
_DISAMBIGUATION_MARK = "~"


def disambiguate_name(base: str, taken, hint: str = "") -> str:
    """*base*, or *base* plus a generic tag when *taken* already holds it.

    Explicitly NOT ``base_2``. A trailing number is how a sequel is written,
    and the comparison key this whole codebase matches names by cannot tell
    the two apart: strip_version_tokens deliberately KEEPS bare numbers, so
    that "Example Game 3" stays a different game from "Example Game" — which
    means the ``MyGame_2`` minted for a mere name collision reduces to
    exactly the slug a genuine "MyGame 2" reduces to. A disambiguator that
    collides with a real sequel is not doing its job, and to the person
    reading a list of folders it simply looks like the second chapter of
    something. ``MyGame~4f2a91`` can be neither.

    The tag comes from *hint* — the thing being named, normally its source
    path — rather than from a counter, which makes it STABLE as well as
    generic: naming the same thing twice lands on the same name instead of
    climbing _2, _3, _4 on every attempt. Without a hint, or if the derived
    tag is somehow taken too, it falls back to random; still generic, just
    not repeatable.

    *taken* is any container of already-used names; the comparison is
    case-insensitive, so pass casefolded values.
    """
    import hashlib
    import uuid
    if not base:
        return base
    used = {str(x).casefold() for x in (taken or ())}
    if base.casefold() not in used:
        return base
    if hint:
        token = hashlib.sha1(str(hint).casefold().encode("utf-8", "replace")).hexdigest()[:6]
        candidate = f"{base}{_DISAMBIGUATION_MARK}{token}"
        if candidate.casefold() not in used:
            return candidate
    while True:
        candidate = f"{base}{_DISAMBIGUATION_MARK}{uuid.uuid4().hex[:6]}"
        if candidate.casefold() not in used:
            return candidate
        if len(used) > 1000:
            logger.warning("disambiguate_name: exhausted %d candidates for %r", len(used), base)
            return candidate


def strip_disambiguation_tag(name: str) -> str:
    """*name* with a tag disambiguate_name may have appended taken back off.

    The inverse of disambiguate_name, and it has to exist as a pair with it:
    anything that GROUPS names spelled the same way — "how many cloud folders
    are there for this title" — has to undo the distinguishing tag first, and
    doing that with an inline regex somewhere else is how the two drift apart.

    Both spellings are accepted, because both exist on disk: the ``~<hex>``
    this mints now, and the historical ``_2`` / ``_3`` that folders created by
    earlier versions still carry.
    """
    import re
    if not name:
        return name
    return re.sub(r"(?:" + re.escape(_DISAMBIGUATION_MARK) + r"[0-9a-f]{4,12}|_\d+)$",
                  "", str(name))


def _normalize_folder_name(name: str) -> str:
    """Sanitize folder name for filesystem."""
    import re
    name = re.sub(r'[<>:"/\\|?*]', '_', name).strip()
    if not name:
        name = "Unknown"
    return name[:128]

def get_folder_name_for_save(game_name: str, exe_path: str, game_id: str = "") -> str:
    """Get sanitized folder name for organizing backups, sync, and icons.
    
    Priority: game_name > exe parent folder (only as fallback when no game name).
    """
    from pathlib import Path
    
    # First: try game name
    name = _normalize_folder_name(game_name) if game_name else ""

    # Second: only fallback to exe parent folder if NO game name at all.
    # Some callers pass save_paths[0] in the exe_path slot — a virtual
    # registry entry there must not be Path()-parsed into a bogus folder
    # name ("Vendor" from registry:HKCU\Software\Vendor\Game).
    if not name and exe_path and not exe_path.lower().startswith("registry:"):
        parent = Path(exe_path).parent
        folder_name = parent.name
        if folder_name and parent != parent.parent:
            name = _normalize_folder_name(folder_name)
    
    # Fallback
    if not name:
        name = "Unknown"
    
    return name

